import * as React from "react";
import { cn } from "./utils";

/**
 * Retokenized shadcn Card. 20-24px radius per the design-direction table
 * (`--radius-card: 22px`), soft/wide/low-opacity elevation, never a raw hex
 * literal.
 */
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-card bg-card text-card-foreground shadow-soft",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

